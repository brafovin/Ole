await wait(page, 1000);
await page.screenshot({ path: 'tests/screenshots/ui_inventory.png' });
await page.click('.tab[data-tab="relics"]');
await wait(page, 500);
await page.screenshot({ path: 'tests/screenshots/ui_relics.png' });
await page.keyboard.press('Tab');
