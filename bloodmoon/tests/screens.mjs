await page.mouse.click(640, 360);
await wait(page, 1500);
await page.screenshot({ path: 'tests/screenshots/ui_menu.png' });
await page.click('[data-act="chars"]');
await wait(page, 1500);
await page.click('[data-char="seraphina"]');
await wait(page, 5000);
await page.screenshot({ path: 'tests/screenshots/ui_charselect.png' });
await page.click('#screen-charselect [data-act="back"]');
await wait(page, 800);
await page.click('[data-act="settings"]');
await wait(page, 900);
await page.screenshot({ path: 'tests/screenshots/ui_settings.png' });
await page.click('#screen-settings [data-act="back"]');
